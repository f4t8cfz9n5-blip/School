export const LEVEL_ORDER: ViolationLevel[] = ['أ', 'ب', 'ج', 'د'];

/** يحاول تخمين المستوى من نص "القرار" كما يرد في تقرير البوابة */
export function guessLevelFromDecision(decision: string): ViolationLevel {
  const d = decision.trim();
  if (d.includes('فصل')) return 'د';
  if (d.includes('إنذار') || d.includes('انذار')) return 'ج';
  if (d.includes('تنبيه')) return 'ب';
  return 'أ';
}

/** يحاول تخمين المستوى من نص "فئة المخالفة" كما يرد في تقرير البوابة (مثال: "الفقرة أ") */
export function guessLevelFromCategoryText(text: string): ViolationLevel {
  const t = text.trim();
  for (const lvl of LEVEL_ORDER) {
    if (t.includes(lvl)) return lvl;
  }
  return 'أ';
}
